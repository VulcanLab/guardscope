#!/usr/bin/env python3
"""F2 delegation fixture: the child program (the receiver side of the
child-process hand-off).

The pi replay adapter (harnesses/pi/adapter/replay.ts) hands each
child-performed action of the F2 trace variants (trace/traces/
baseline-f2.yaml, baseline-f2h2.yaml) to THIS program: it spawns it with the
delegation chain ids in its environment (the carrier is "env") and the job
on stdin as JSON — the compiled action plan to perform, plus the relay flag
for the two-hop variant.

The job on stdin:
    {"run_id": "...",           the run identity (INSPECTION_RUN_ID)
     "relay": false | true,     hop 2: hand the work one level further down
     "actions": [...]}          compiled action plans (kind + arguments)

The chain ids come from the environment, never from the job (that is the
point of the env carrier):
    F2_DELEGATION_ID          this hand-off's id (generated by the giver)
    F2_PARENT_DELEGATION_ID   the hand-off that caused this one ("" at root)
    F2_ROOT_DELEGATION_ID     the root of the chain
    F2_HOP                    1 = handed directly from the parent agent

What this program does, in order:

1. ACCEPT the hand-off: append one delegation-record/1 line (event
   "accepted") to delegation-records.jsonl on the replay volume (REPLAY_LOG_DIR,
   /workspace/replay in the container) — the same file the adapter wrote its
   "sent" line into. Sent and accepted are different facts: a hand-off the
   receiver never took must stay visible, not be silently merged away.
2. Write a marker file (f2-marker-<delegation_id>.json) proving this child
   actually ran, carrying the chain ids it received — child-liveness
   evidence that outlives the child process.
3. Either (relay: false) perform the effects — file write, network connect,
   program start; the same executors' semantics as the adapter's in-process
   ones — or (relay: true, the two-hop variant) perform ONE MORE hand-off:
   generate a fresh delegation id, append its "sent" line (the came-from
   pointer and the chain root travel down), spawn ITSELF with the new ids in
   the grandchild's environment, and relay the grandchild's report up. The
   child is then a pure intermediary; the grandchild performs the effects.
4. Report on stdout as JSON:
   {"status": "ok" | "error", "delegation_id": <echo>,
    "actor": ..., "results": [{id, status, detail | error}...]}
   The delegation_id echo is what the run's per-action trace-back joins on
   (framework/delegation.py trace_back, method "id-echo" — an exact echo
   attributes, no guessing). For hop 2 the relayed report echoes the
   GRANDCHILD's hand-off id, so the traced chain is [root, ..., deepest].

Records are emitted exactly per delegation-record/1 (framework/schemas/
delegation-record/1.schema.json, frozen): channel "child" (a child process
on the same machine), protocol "stdio" (the job crosses the child's stdin),
carrier "env", machine "origin" (this hand-off never leaves the harness
machine; "executor" is for hand-offs that cross to another machine, and
results from different machines are never pooled).

Exit codes: 0 with a JSON report on stdout even when an action failed (the
report says so — a failed effect is a result, not a broken child); 2 for a
broken job or missing chain ids (nothing was performed; the reason goes to
stderr).

Run stand-alone (what the tests do; no container needed):
    REPLAY_LOG_DIR=/tmp/x F2_DELEGATION_ID=d1 F2_ROOT_DELEGATION_ID=d1 \
    F2_HOP=1 python3 f2-helper.py <<< '{"run_id": "r", "actions": [...]}'
"""

from __future__ import annotations

import hashlib
import json
import os
import socket
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

RECORDS_NAME = "delegation-records.jsonl"
MARKER_PREFIX = "f2-marker-"
# Crockford base32 (the delegation-record/1 record_id alphabet: no I, L, O, U)
_CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
# Mirrors the adapter's per-kind action timeouts (ACTION_TIMEOUT_MS); the
# child is not allowed to outlive the replay window.
ACTION_TIMEOUT_S = 20
GRANDCHILD_TIMEOUT_S = 30


def _fail(reason: str) -> "None":
    """Nothing was performed; say why on stderr and exit 2."""
    print(f"f2-helper: {reason}", file=sys.stderr)
    raise SystemExit(2)


# --- record identity ------------------------------------------------------------

def ulid() -> str:
    """record_id (delegation-record/1): a ULID — 48-bit millisecond
    timestamp + 80 random bits, Crockford base32, 26 chars."""
    raw = int.from_bytes(os.urandom(10), "big")
    val = (int(time.time() * 1000) << 80) | raw
    return "".join(_CROCKFORD[(val >> (5 * i)) & 31] for i in range(25, -1, -1))


def now_rfc3339_ms() -> str:
    dt = datetime.now(timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%S.") + f"{dt.microsecond // 1000:03d}Z"


def new_delegation_id() -> str:
    """Opaque and unique is the only requirement (the giver generates it);
    timestamp + random hex is enough."""
    return f"d-{int(time.time() * 1000):x}-{os.urandom(6).hex()}"


def task_digest(action_ids: list[str]) -> str:
    """A digest of the handed task — the sorted action ids, no payloads.
    Byte-identical to the adapter's digest for the same ids, so the two
    sides' records can be joined on it."""
    payload = json.dumps(sorted(action_ids), separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()[:16]


def actor_name(hop: int) -> str:
    """The receiving role at this depth: hop 1 is the child, hop 2 the
    grandchild; deeper hops keep the numbering visible."""
    return {1: "f2-child", 2: "f2-grandchild"}.get(hop, f"f2-child-{hop}")


# --- the hand-off records ---------------------------------------------------------

def read_env_chain() -> dict:
    """The chain ids from the environment (the env carrier). A missing
    delegation id means no hand-off happened: refuse, never invent one."""
    did = os.environ.get("F2_DELEGATION_ID", "").strip()
    if not did:
        _fail("no F2_DELEGATION_ID in the environment — this process was "
              "spawned without a hand-off (the env carrier is missing)")
    return {
        "delegation_id": did,
        "parent": os.environ.get("F2_PARENT_DELEGATION_ID", "").strip() or None,
        "root": os.environ.get("F2_ROOT_DELEGATION_ID", "").strip() or did,
        "hop": int(os.environ.get("F2_HOP", "1")),
    }


def write_record(rec: dict, log_dir: Path) -> None:
    """Append one delegation-record/1 line to the replay volume's stream.
    Record emission must never break the child (a lost line is a reported
    problem downstream, never a lost effect)."""
    log_dir.mkdir(parents=True, exist_ok=True)
    with open(log_dir / RECORDS_NAME, "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, sort_keys=True) + "\n")


def delegation_record(event: str, *, run_id: str, stream_id: str, seq: int,
                      chain: dict, from_actor: str, to_actor: str | None,
                      digest: str, actor_pid: int) -> dict:
    """One delegation-record/1, exactly per the frozen schema: who handed
    what to whom, through which channel, on which machine, and (through the
    parent pointer) which earlier hand-off caused this one."""
    return {
        "schema": 1,
        "record_id": ulid(),
        "run_id": run_id,
        "stream_id": stream_id,
        "seq": seq,
        "ts": now_rfc3339_ms(),
        "event": event,
        "channel": "child",
        "delegation_id": chain["delegation_id"],
        "parent_delegation_id": chain["parent"],
        "root_delegation_id": chain["root"],
        "hop": chain["hop"],
        "from_actor": from_actor,
        "to_actor": to_actor,
        "task_digest": digest,
        "protocol": "stdio",
        "machine": "origin",
        "carrier": "env",
        "actor_pid": actor_pid,
    }


# --- the effects (the same executor semantics as the adapter's) -------------------

def perform_action(action: dict) -> dict:
    """Perform one compiled action plan's effect from this process. The
    kinds are the process-level effect ones (the F2 variants delegate
    exactly those); a tool-transport kind in a child job is a fixture
    mistake and is refused, not improvised."""
    kind = action.get("kind")
    if kind == "file_write":
        path = Path(action["path"])
        path.parent.mkdir(parents=True, exist_ok=True)
        data = action.get("data", "")
        if action.get("append"):
            with open(path, "a", encoding="utf-8") as f:
                f.write(data)
        else:
            path.write_text(data, encoding="utf-8")
        return {"path": str(path), "bytes": len(data.encode())}
    if kind == "tcp_connect":
        with socket.create_connection((action["host"], int(action["port"])),
                                      timeout=ACTION_TIMEOUT_S) as sock:
            sock.sendall(action.get("payload", "").encode())
        return {"host": action["host"], "port": int(action["port"])}
    if kind == "udp_send":
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.sendto(action.get("payload", "").encode(),
                       (action["host"], int(action["port"])))
        return {"host": action["host"], "port": int(action["port"])}
    if kind == "spawn":
        proc = subprocess.run(action["cmd"], capture_output=True,
                              timeout=ACTION_TIMEOUT_S)
        if proc.returncode != 0:
            raise RuntimeError(
                f"spawned {action['cmd']} exited {proc.returncode}")
        return {"cmd": action["cmd"]}
    if kind == "credential_read":
        data = Path(action["path"]).read_bytes()
        return {"path": action["path"], "bytes": len(data)}
    raise ValueError(f"unsupported kind {kind!r} for a child-performed "
                     f"action {action.get('id')!r}")


def perform_actions(actions: list[dict]) -> list[dict]:
    """One result row per action (ok detail | error), in job order. A failed
    action is recorded, never hidden: the report carries it to the adapter
    like the replay log carries a failed in-process action."""
    results = []
    for action in actions:
        try:
            results.append({"id": action.get("id"), "status": "ok",
                            "detail": perform_action(action)})
        except Exception as exc:  # the effect failed — say so, keep going
            results.append({"id": action.get("id"), "status": "error",
                            "error": str(exc)})
    return results


# --- the one-more-hand-off (the two-hop variant) -----------------------------------

def relay_to_grandchild(job: dict, chain: dict, log_dir: Path,
                        seq: int) -> dict:
    """Hop 2: this child hands the whole job one level further down and
    relays the grandchild's report up (verbatim, so the echoed delegation id
    stays the grandchild's — the chain the trace-back walks is
    [root, child, grandchild], not a chain that stops at the relay)."""
    child_id = new_delegation_id()
    grand_chain = {
        "delegation_id": child_id,
        "parent": chain["delegation_id"],
        "root": chain["root"],
        "hop": chain["hop"] + 1,
    }
    digest = task_digest([a.get("id") for a in job.get("actions", [])])
    write_record(delegation_record(
        "sent", run_id=job.get("run_id", "unattributed"),
        stream_id=f"{actor_name(chain['hop'])}-{os.getpid()}",
        seq=seq, chain=grand_chain,
        from_actor=actor_name(chain["hop"]),
        to_actor=actor_name(chain["hop"] + 1),
        digest=digest, actor_pid=os.getpid()), log_dir)
    # the ids travel down via env, exactly as the adapter passed them here
    env = dict(os.environ)
    env.update({
        "F2_DELEGATION_ID": grand_chain["delegation_id"],
        "F2_PARENT_DELEGATION_ID": grand_chain["parent"],
        "F2_ROOT_DELEGATION_ID": grand_chain["root"],
        "F2_HOP": str(grand_chain["hop"]),
    })
    grand_job = dict(job)
    grand_job["relay"] = False
    try:
        proc = subprocess.run(
            [sys.executable, str(Path(__file__).resolve())],
            input=json.dumps(grand_job), capture_output=True, text=True,
            env=env, timeout=GRANDCHILD_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return {"status": "error",
                "delegation_id": grand_chain["delegation_id"],
                "actor": actor_name(grand_chain["hop"]),
                "results": [], "error": "grandchild timed out"}
    if proc.returncode != 0:
        return {"status": "error",
                "delegation_id": grand_chain["delegation_id"],
                "actor": actor_name(grand_chain["hop"]),
                "results": [],
                "error": f"grandchild exited {proc.returncode}: "
                         f"{proc.stderr.strip()[:300]}"}
    return json.loads(proc.stdout)


# --- main --------------------------------------------------------------------------

def main() -> None:
    try:
        job = json.loads(sys.stdin.read())
    except json.JSONDecodeError as exc:
        _fail(f"the job on stdin is not JSON ({exc})")
        return
    if not isinstance(job, dict) or not isinstance(job.get("actions"), list):
        _fail("the job on stdin must be an object with an 'actions' list")
        return

    chain = read_env_chain()
    log_dir = Path(os.environ.get("REPLAY_LOG_DIR", "/workspace/replay"))
    run_id = job.get("run_id", "unattributed")
    hop = chain["hop"]
    me = actor_name(hop)
    digest = task_digest([a.get("id") for a in job["actions"]])

    # 1. the acceptance: the receiver took the work (the giver is the
    #    parent agent at hop 1, this child's own role one level up deeper)
    write_record(delegation_record(
        "accepted", run_id=run_id, stream_id=f"{me}-{os.getpid()}", seq=0,
        chain=chain,
        from_actor="pi-root" if hop == 1 else actor_name(hop - 1),
        to_actor=me, digest=digest, actor_pid=os.getpid()), log_dir)

    # 2. the marker file: this child actually ran, carrying the chain ids
    marker = {
        "run_id": run_id,
        "delegation_id": chain["delegation_id"],
        "parent_delegation_id": chain["parent"],
        "root_delegation_id": chain["root"],
        "hop": hop,
        "actor": me,
        "pid": os.getpid(),
        "action_ids": [a.get("id") for a in job["actions"]],
        "ts": now_rfc3339_ms(),
    }
    try:
        write_marker(marker, log_dir)
    except OSError:
        pass  # the marker is liveness evidence, never a failure mode

    # 3. either relay one more hand-off down, or perform the effects here
    if job.get("relay"):
        report = relay_to_grandchild(job, chain, log_dir, seq=1)
    else:
        results = perform_actions(job["actions"])
        ok = all(r["status"] == "ok" for r in results)
        report = {
            "status": "ok" if ok else "error",
            "delegation_id": chain["delegation_id"],
            "actor": me,
            "results": results,
        }
        if not ok:
            report["error"] = "; ".join(
                f"{r['id']}: {r['error']}" for r in results
                if r["status"] == "error")

    # 4. the report goes to the adapter (stdout); a failed effect is still
    #    a completed hand-off, so the exit code stays 0
    sys.stdout.write(json.dumps(report, sort_keys=True) + "\n")


def write_marker(marker: dict, log_dir: Path) -> None:
    log_dir.mkdir(parents=True, exist_ok=True)
    path = log_dir / f"{MARKER_PREFIX}{marker['delegation_id']}.json"
    path.write_text(json.dumps(marker, sort_keys=True) + "\n",
                    encoding="utf-8")


if __name__ == "__main__":
    main()
